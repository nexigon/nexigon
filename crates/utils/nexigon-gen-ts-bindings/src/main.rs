//! Generate TypeScript action types and their output checker table.

use nexigon_api::with_actions;

pub fn main() {
    println!("// This file is automatically generated.");
    println!("// Do not edit this file manually.");
    println!("\nimport type {{ Checker }} from '@sidex/types'");
    println!("\nimport * as types from './types/index.js'");
    println!("\nexport type Actions = {{");
    let mut checkers = Vec::new();
    macro_rules! print_action_type {
        ($(($name:literal, $variant:ident, $input:path, $output:path),)*) => {
            $(
                let input_parts = stringify!($input)
                    .split("::")
                    .map(|p| p.trim())
                    .collect::<Vec<_>>();
                let output_parts = stringify!($output)
                    .split("::")
                    .map(|p| p.trim())
                    .collect::<Vec<_>>();
                let input_type = input_parts.join(".");
                let output_type = output_parts.join(".");
                println!(
                    "  {}: {{ input: types.{input_type}; output: types.{output_type} }};",
                    stringify!($name)
                );
                checkers.push(format!(
                    "  {}: types.{output_type},",
                    stringify!($name)
                ));
            )*
        };
    }
    with_actions!(print_action_type);
    println!("}};");
    println!(
        "\nexport const ActionOutputs: {{ [A in keyof Actions]: Checker<Actions[A]['output']> }} = {{"
    );
    for checker in checkers {
        println!("{checker}");
    }
    println!("}};")
}
